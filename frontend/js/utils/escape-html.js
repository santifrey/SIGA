/**
 * SIGA - utils/escape-html.js
 * Utilidad de sanitización para prevenir vulnerabilidades XSS en templates innerHTML.
 */

export function escapeHtml(value) {
  if (value === null || value === undefined) return '';
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
